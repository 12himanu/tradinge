/**
 * Both sides of the boundary, checked against the schemas the engine exports (P4D-09).
 *
 * These tests are the reason a contract change cannot pass silently: the request we build is
 * validated field by field against `analysis_request.schema.json`, and the fixtures we map are
 * real engine output, regenerated by running the engine CLI.
 */

/**
 * @return array<string, mixed>
 */
function engineSchema(string $name): array
{
    $path = base_path("../ai-engine/contracts/{$name}.schema.json");

    return json_decode((string) file_get_contents($path), true, 512, JSON_THROW_ON_ERROR);
}

/**
 * A deliberately small structural check: every required property present, no unknown properties
 * (the engine's models are `extra="forbid"`, so an extra key is a 422 at runtime).
 *
 * @param  array<string, mixed>  $payload
 * @param  array<string, mixed>  $schema
 * @return list<string>
 */
function schemaViolations(array $payload, array $schema, string $path = ''): array
{
    $problems = [];
    $properties = is_array($schema['properties'] ?? null) ? $schema['properties'] : [];

    foreach ($schema['required'] ?? [] as $required) {
        if (! array_key_exists($required, $payload)) {
            $problems[] = "missing required field {$path}{$required}";
        }
    }

    if (($schema['additionalProperties'] ?? true) === false) {
        foreach (array_keys($payload) as $key) {
            if (! array_key_exists($key, $properties)) {
                $problems[] = "unknown field {$path}{$key}";
            }
        }
    }

    return $problems;
}

function analysisWithBars(int $bars = 120): Analysis
{
    $stock = Stock::factory()->create(['symbol' => 'HDL']);
    $analysis = Analysis::factory()->create([
        'stock_id' => $stock->id,
        'timeframe' => Timeframe::D1,
        'status' => AnalysisStatus::Queued,
    ]);

    // Dates are immutable app-wide (Date::use(CarbonImmutable::class)), so advance explicitly.
    $date = now()->startOfDay()->subDays($bars);
    for ($i = 0; $i < $bars; $i++) {
        $date = $date->addDay();
        PriceBar::factory()->create([
            'stock_id' => $stock->id,
            'timeframe' => Timeframe::D1,
            'bar_time' => $date,
        ]);
    }

    return $analysis;
}

it('builds a request that satisfies the engine schema', function () {
    $analysis = analysisWithBars();

    $payload = app(EngineRequestBuilder::class)->build($analysis);
    $schema = engineSchema('analysis_request');

    expect(schemaViolations($payload, $schema))->toBe([]);
});

it('sends bars in ascending order with the fields the engine expects', function () {
    $payload = app(EngineRequestBuilder::class)->build(analysisWithBars(80));

    expect($payload['bars'])->toHaveCount(80);

    $dates = array_column($payload['bars'], 'date');
    $sorted = $dates;
    sort($sorted);
    expect($dates)->toBe($sorted)
        ->and(array_keys($payload['bars'][0]))->toBe(['date', 'open', 'high', 'low', 'close', 'volume']);
});

it('caps the number of bars it sends', function () {
    $payload = app(EngineRequestBuilder::class)->build(analysisWithBars(EngineRequestBuilder::MAX_BARS + 40));

    expect($payload['bars'])->toHaveCount(EngineRequestBuilder::MAX_BARS);
});

it('sends no bars when the chart is not linked to a stock', function () {
    $analysis = Analysis::factory()->create(['stock_id' => null]);

    $payload = app(EngineRequestBuilder::class)->build($analysis);

    expect($payload['bars'])->toBe([])->and($payload['symbol'])->toBeNull();
});

it('derives NEPSE fees from the exchange schedule', function () {
    $payload = app(EngineRequestBuilder::class)->build(analysisWithBars(70));

    // Broker commission tier + SEBON fee + the amortised DP charge: well under 1% a side.
    expect($payload['fees']['buy_pct'])->toBeGreaterThan(0.3)
        ->and($payload['fees']['buy_pct'])->toBeLessThan(1.0)
        ->and($payload['fees']['sell_pct'])->toBeGreaterThan(0.3);
});

it('maps a Tier A result into rows the database accepts', function () {
    $analysis = analysisWithBars(70);

    app(PersistAnalysisResult::class)($analysis, engineResultFixture(), durationMs: 1234);
    $analysis->refresh();

    expect($analysis->status)->toBe(AnalysisStatus::Completed)
        ->and($analysis->data_tier)->toBe(DataTier::Ohlcv)
        ->and($analysis->decision)->toBe(Decision::Buy)
        ->and($analysis->setup_score)->toBe(77)
        ->and($analysis->duration_ms)->toBe(1234)
        ->and($analysis->report_markdown)->toContain('Decision: BUY')
        ->and($analysis->engine_version)->not->toBeNull();

    expect($analysis->indicators)->toHaveCount(10)
        ->and($analysis->levels)->not->toBeEmpty()
        ->and($analysis->patterns->where('category', PatternCategory::Smc))->not->toBeEmpty()
        ->and($analysis->predictions)->toHaveCount(2);
});

it('keeps the evidence bundle for reproducibility', function () {
    $analysis = analysisWithBars(70);

    app(PersistAnalysisResult::class)($analysis, engineResultFixture(), durationMs: 10);

    $evidence = $analysis->refresh()->evidence;
    expect($evidence['items'])->not->toBeEmpty()
        ->and($evidence['score']['factors'])->not->toBeEmpty()
        ->and($evidence['timings'])->not->toBeEmpty();
});

it('maps a Tier C result without inventing numbers', function () {
    $analysis = analysisWithBars(70);

    app(PersistAnalysisResult::class)($analysis, engineResultFixture('tier_c_result.json'), durationMs: 10);
    $analysis->refresh();

    expect($analysis->status)->toBe(AnalysisStatus::Partial)
        ->and($analysis->data_tier)->toBe(DataTier::VisionOnly)
        ->and($analysis->setup_score)->toBeNull()
        ->and($analysis->decision_limited)->toBeTrue()
        ->and($analysis->predictions)->toHaveCount(0)
        ->and($analysis->levels)->toHaveCount(0);
});

it('writes predictions with a trading-calendar expiry', function () {
    $analysis = analysisWithBars(70);

    app(PersistAnalysisResult::class)($analysis, engineResultFixture(), durationMs: 10);

    $bias = $analysis->refresh()->predictions->firstWhere('kind', PredictionKind::DirectionalBias);
    expect($bias)->not->toBeNull()
        ->and($bias->horizon_bars)->toBe(20)
        ->and($bias->status)->toBe(PredictionStatus::Active)
        // 20 NEPSE sessions is about four calendar weeks, never 20 calendar days.
        ->and($bias->as_of->diffInDays($bias->expires_at))->toBeGreaterThan(20);
});

it('does not duplicate predictions when the same analysis is persisted twice', function () {
    $analysis = analysisWithBars(70);
    $result = engineResultFixture();

    app(PersistAnalysisResult::class)($analysis, $result, durationMs: 10);
    app(PersistAnalysisResult::class)($analysis, $result, durationMs: 10);

    expect($analysis->refresh()->predictions)->toHaveCount(2)
        ->and($analysis->indicators)->toHaveCount(10);
});
